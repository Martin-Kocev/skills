  function viewSearch() {
    var initial = parseRoute().query.q || '';
    var results = h('div', { class: 'search-view__results', 'aria-live': 'polite' });
    var input = h('input', {
      class: 'search-view__input', type: 'search', value: initial,
      placeholder: T('views.search.placeholder'), 'aria-label': T('views.search.ariaLabel'),
      oninput: function (e) { fill(e.target.value); }
    });

    /* An empty query is not an empty screen: it is the moment to say what the
       index actually contains, so the reader can tell whether their question
       is answerable here before they type it. */
    function fill(query) {
      results.innerHTML = '';
      var q = String(query || '').trim();
      if (!q) {
        var counts = {};
        Object.keys(byId).forEach(function (id) { counts[byId[id].kind] = (counts[byId[id].kind] || 0) + 1; });
        results.appendChild(h('div', { class: 'search-index-summary' }, [
          h('h3', { text: T('views.search.indexHeading') }),
          h('p', { text: T('views.search.indexBody', { count: Object.keys(byId).length }) }),
          h('div', { class: 'stack-badges' }, Object.keys(counts).sort().map(function (kind) {
            return h('span', { text: kindLabel(kind) + ' · ' + counts[kind] });
          }))
        ]));
        return;
      }
      var hits = searchRecords(q);
      if (!hits.length) {
        results.appendChild(UI.empty('views.search.noResults', { query: q }));
        return;
      }
      var groups = {};
      hits.forEach(function (rec) { (groups[rec.kind] = groups[rec.kind] || []).push(rec); });
      Object.keys(groups).sort().forEach(function (kind) {
        results.appendChild(h('section', { class: 'search-result-group' }, [
          h('h3', { text: kindLabel(kind) + ' · ' + groups[kind].length }),
          h('ul', { class: 'search-result-list' }, groups[kind].map(function (rec) {
            return h('li', {}, [h('button', { onclick: function () { goToItem(rec.item.id); } }, [
              h('span', { class: 'title', text: titleOf(rec.item) }),
              h('span', { class: 'state', text: searchReason(rec, q) })
            ])]);
          }))
        ]));
      });
    }

    fill(initial);
    return h('div', {}, [UI.sectionHead('search'), input, results]);
  }

