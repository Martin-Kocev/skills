  function viewHome() {
    var s = P.summary(trackedIds());
    var started = s.started + s.viewed + s.completed > 0;
    // On a first visit the dominant action is the first authored path; once
    // there is a reading history it becomes "continue", so the loudest button
    // on the page is never asking the reader to start over.
    var preferred = started
      ? (A.learningPaths || []).filter(function (p) { return p.kind === 'continue'; })[0]
      : (A.learningPaths || [])[0];

    var out = h('div', {}, [h('section', { class: 'harbor-hero' }, [
      h('div', { class: 'harbor-hero__copy' }, [
        h('div', { class: 'location-line' }, [icon('compass', 14), txt(T('views.home.locationLine', { repo: A.repository.name }))]),
        h('h1', { text: A.meta.title || A.repository.name }),
        h('p', { class: 'lede', text: A.meta.oneLiner || '' }),
        A.meta.hook ? prose(A.meta.hook, { class: 'hook' }) : null,
        h('div', { class: 'stack-badges' }, (A.meta.stack || []).map(function (x) { return h('span', { text: x }); })),
        preferred ? h('button', { class: 'btn-primary btn-primary--hero', onclick: function () { startPath(preferred); } },
          [icon('ship', 18), txt(T(started ? 'views.home.continueAction' : 'views.home.startAction'))]) : null
      ]),
      worldPreview(),
      h('div', { class: 'harbor-progress' }, [
        h('span', { text: T('views.home.exploredLabel') }),
        h('strong', { text: s.percent + '%' }),
        h('div', { class: 'meter' }, [h('i', { style: 'width:' + s.percent + '%' })]),
        h('small', { text: T('views.home.exploredDetail', { completed: s.completed, total: s.total }) })
      ])
    ])]);
    staleNotices().forEach(function (n) { out.appendChild(n); });

    var paths = (A.learningPaths || []).filter(function (p) {
      if (p.kind === 'continue') return s.completed + s.viewed + s.started > 0;
      if (p.kind === 'what-changed') return (A.updateHistory || []).length > 1;
      // "Unfinished" needs something started. On a first visit every section is
      // merely unread, and offering to revisit 41 things nobody has opened is
      // noise — the same reason "Continue" is hidden until there is a location.
      if (p.kind === 'review-unfinished') {
        return s.bookmarked + s.unclear > 0 ||
               (s.completed + s.viewed + s.started > 0 && s.completed < s.total);
      }
      return true;
    });

    out.appendChild(h('h2', { class: 'home__paths-heading', text: T('views.home.pathsHeading') }));
    out.appendChild(h('div', { class: 'grid grid--paths' }, paths.map(function (p) {
      return h('button', { class: 'path-card', onclick: function () { startPath(p); } }, [
        h('span', { class: 'path-card__title', text: p.title }),
        h('span', { class: 'path-card__blurb', text: p.blurb || '' }),
        h('span', { class: 'path-card__meta', text: pathMeta(p, s) })
      ]);
    })));

    if (A.meta.scopeNote) out.appendChild(h('p', { class: 'home__scope', text: A.meta.scopeNote }));
    return out;
  }

