  function startPlay(wf, i) {
    var steps = wf.steps || [];
    var idx = i;
    playTimer = setInterval(function () {
      idx += 1;
      if (idx >= steps.length) return stopPlay(), render();
      go('#/workflows/' + wf.id + '/' + idx);
      if (idx >= steps.length - 1) stopPlay();
    }, playbackDelay());
    render();
  }
