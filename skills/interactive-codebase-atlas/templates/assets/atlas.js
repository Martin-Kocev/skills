  /** complete / bookmark / unclear — completion is always the reader's call. */
  function itemActions(id) {
    var it = P.item(id);
    var row = h('div', { class: 'item-actions' });
    function btn(iconName, label, pressed, fn) {
      return h('button', {
        class: 'control', 'aria-pressed': pressed ? 'true' : 'false',
        onclick: function () { fn(); render(); }
      }, [icon(iconName), txt(label)]);
    }
    row.appendChild(btn('circleCheck', T(it.state === 'completed' ? 'actions.completed' : 'actions.complete'),
      it.state === 'completed', function () { P.toggleComplete(id); }));
    row.appendChild(btn('bookmark', T(it.bookmarked ? 'actions.bookmarked' : 'actions.bookmark'),
      it.bookmarked, function () { P.toggleFlag(id, 'bookmarked'); }));
    row.appendChild(btn('question', T(it.unclear ? 'actions.unclearOn' : 'actions.unclear'),
      it.unclear, function () { P.toggleFlag(id, 'unclear'); }));
    /* Every tracked section is a stop on the full tour, so the forward edge
       belongs here — beside the actions the reader just used — rather than only
       on the tour index. Without it, following the order means returning to
       that index fifty times. */
    return frag([row, tourNext(id)]);
  }

  /**
   * The tour's forward edge on a section page. Deliberately not `nextAction`:
   * the end of a workflow already uses that for "back to the guided tours", and
   * two identical blocks stacked would read as one control repeated.
   */
  function tourNext(id) {
    var seq = tourSequence();
    var i = seq.indexOf(id);
    if (i === -1 || i === seq.length - 1) return null;
    var nextId = seq[i + 1];
    return h('a', { class: 'tour-next', href: linkFor(nextId) }, [
      h('span', { class: 'tour-next__meta' }, [
        icon('route', 14),
        txt(T('views.tour.stopLabel', { n: i + 2, total: seq.length }))
      ]),
      h('span', { class: 'tour-next__title' }, [
        h('span', { class: 'label', text: T('views.tour.nextUpLead') }),
        h('strong', { text: labelOf(nextId) })
      ]),
      icon('arrowRight', 16)
    ]);
  }

  function nextAction(label, routeHash, hint) {
    return h('div', { class: 'next-action' }, [
      h('div', {}, [h('span', { class: 'label', text: T('actions.nextLabel') }), h('div', { text: hint || label })]),
      h('button', { class: 'btn-primary', text: label, onclick: function () { go(routeHash); } })
    ]);
  }

