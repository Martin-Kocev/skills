  function badges(item, updatedOverride) {
    var kids = [];
    if (item.confidence) {
      kids.push(h('span', {
        class: 'badge badge--' + item.confidence,
        title: T('badges.confidenceTitles.' + item.confidence),
        text: item.confidence
      }));
    }
    if (item.changed && item.changed.state && item.changed.state !== 'unchanged') {
      kids.push(h('span', { class: 'badge badge--' + item.changed.state }, [
        txt(item.changed.state),
        item.changed.commit ? h('code', { class: 'hash', text: item.changed.commit }) : null
      ]));
    }
    if (updatedOverride === true || (updatedOverride !== false && P.isUpdatedSinceSeen(item.id, hashes[item.id]))) {
      kids.push(h('span', { class: 'badge badge--updated', text: T('badges.updatedSinceSeen') }));
    }
    return kids.length ? h('div', { class: 'badge-row' }, kids) : null;
  }

  function sources(list, label) {
    if (!list || !list.length) return null;
    return h('div', { class: 'srcs', 'data-focus-hide': true }, [
      label ? h('span', { class: 'src', html: '<b>' + esc(label) + '</b>' }) : null
    ].concat(list.map(function (s) {
      var line = s.path + (s.lines ? ':' + s.lines[0] : '');
      return h('span', { class: 'src', title: s.note || '', html: (s.symbol ? '<b>' + esc(s.symbol) + '</b> ' : '') + esc(line) });
    })));
  }

  function whys(item) {
    if (!item.why || !item.why.length) return null;
    return frag(item.why.map(function (w) {
      return h('details', { class: 'disclose' }, [
        h('summary', { text: w.q }),
        h('div', {}, [
          prose(w.a),
          w.confidence ? h('span', { class: 'badge badge--' + w.confidence, text: w.confidence }) : null,
          sources(w.sources)
        ])
      ]);
    }));
  }

  function conflictNote(item) {
    if (!item.conflict) return null;
    return h('div', { class: 'notice' }, [h('div', {}, [
      h('strong', { text: T('notices.conflict.strong') }),
      mark(T('notices.conflict.body', { claim: item.conflict.claim, reality: item.conflict.reality })),
      item.conflict.assessment ? h('em', { text: item.conflict.assessment }) : null
    ])]);
  }

  function excerpt(ex) {
    if (!ex || !ex.code) return null;
    return frag([
      h('pre', { class: 'excerpt' }, [h('code', { text: ex.code })]),
      ex.caption ? h('p', { class: 'excerpt-cap', text: ex.caption }) : null
    ]);
  }

