  /**
   * The atlas tracks fifty sections and the rail is a menu, not a sequence —
   * so this is the one place that answers "in what order do I read all of it".
   *
   * Stages are authored in ui.json by atlas.json COLLECTION NAME, never by a
   * list of ids: a regenerated atlas then files each new section into the right
   * stage by itself, where an id list would quietly rot. Reading order inside a
   * stage is the collection's own authored order, which already runs from the
   * screen a visitor touches inward to the stores behind it.
   */
  function tourStages() {
    var out = [];
    UI.get('views.tour.stages', []).forEach(function (stage) {
      var ids = [];
      (stage.kinds || []).forEach(function (kind) {
        var coll = A[kind];
        // `auth` and `delivery` are single objects; every other kind is a list.
        if (Array.isArray(coll)) {
          coll.forEach(function (item) { if (item && item.id && byId[item.id]) ids.push(item.id); });
        } else if (coll && coll.id && byId[coll.id]) {
          ids.push(coll.id);
        }
      });
      if (ids.length) out.push({ id: stage.id, title: stage.title, blurb: stage.blurb, ids: ids });
    });
    return out;
  }

  /** Every stop flattened, which is what numbering and "next" both read. */
  function tourSequence() {
    return tourStages().reduce(function (all, stage) { return all.concat(stage.ids); }, []);
  }

  function viewTour() {
    var stages = tourStages();
    var seq = tourSequence();
    if (!seq.length) return h('div', {}, [UI.sectionHead('tour'), UI.empty('views.tour.empty')]);

    var completed = seq.filter(function (id) { return P.state(id) === 'completed'; });
    // The first stop not yet marked complete — not the first unopened one, so
    // skipping ahead and coming back does not send the reader to the beginning.
    var nextId = seq.filter(function (id) { return P.state(id) !== 'completed'; })[0];
    var percent = seq.length ? Math.round((completed.length / seq.length) * 100) : 0;
    var started = completed.length > 0;

    /* The button carries the verb and the line above it carries the destination:
       a primary button labelled "React SPA" states a noun where the reader is
       looking for an action. */
    var head = nextId
      ? nextAction(
          T(started ? 'views.tour.continueAction' : 'views.tour.startAction'),
          linkFor(nextId),
          T('views.tour.stopLabel', { n: seq.indexOf(nextId) + 1, total: seq.length }) +
            T('common.middot') + labelOf(nextId))
      : h('div', { class: 'next-action tour-done' }, [
          h('div', {}, [
            h('strong', { text: T('views.tour.doneTitle') }),
            h('p', { text: T('views.tour.doneBody', { total: seq.length }) })
          ]),
          h('button', {
            class: 'btn-primary', text: T('views.tour.reviewAction'),
            onclick: function () { goToItem(seq[0]); }
          })
        ]);

    var n = 0;
    return h('div', {}, [
      UI.sectionHead('tour'),
      h('div', { class: 'meter meter--wide' }, [h('i', { style: 'width:' + percent + '%' })]),
      h('span', { class: 'meter-label', text: T('views.tour.progressSummary', {
        completed: completed.length, total: seq.length }) }),
      head,
      h('ol', { class: 'tour-stages' }, stages.map(function (stage) {
        var doneHere = stage.ids.filter(function (id) { return P.state(id) === 'completed'; }).length;
        return h('li', { class: 'tour-stage', 'data-complete': doneHere === stage.ids.length ? 'true' : null }, [
          h('div', { class: 'tour-stage__head' }, [
            h('h3', { text: stage.title }),
            h('span', { class: 'state', text: T('views.tour.stageMeta', {
              completed: doneHere, total: stage.ids.length }) })
          ]),
          stage.blurb ? prose(stage.blurb, { class: 'tour-stage__blurb' }) : null,
          h('ol', { class: 'tour-stops', 'aria-label': T('views.tour.stageNavLabel', { stage: stage.title }) },
            stage.ids.map(function (id) {
              n += 1;
              var state = P.state(id);
              return h('li', { 'data-state': state, 'data-current': id === nextId ? 'true' : null }, [
                h('span', { class: 'tour-stops__n', text: String(n) }),
                h('span', { class: 'title' }, [h('a', { href: linkFor(id), text: labelOf(id) })]),
                h('span', { class: 'state', 'data-state': state }, [
                  icon(stateIcon(state), 13), txt(stateLabel(state))
                ])
              ]);
            }))
        ]);
      }))
    ]);
  }

