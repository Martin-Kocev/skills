  /* Step counts, never time estimates — and only where a count means something.
     A free-roam path has no length, and "1 steps" is not a sentence. */
  function pathMeta(p, summary) {
    var base = 'views.home.pathMeta.';
    if (p.kind === 'explore' || p.kind === 'continue' || p.kind === 'what-changed') return T(base + p.kind);
    if (p.kind === 'reading-order') {
      var read = P.summary(readingNodes().map(function (n) { return n.id; }));
      return T(base + 'reading-order', { count: read.total - read.completed });
    }
    if (p.kind === 'review-unfinished') {
      var open = summary.total - summary.completed;
      return T(base + 'review-unfinished', { count: summary.bookmarked + summary.unclear + open });
    }
    if (p.kind === 'follow-one-action') {
      var wf = byId[(p.stepIds || [])[0]];
      var n = wf && wf.item.steps ? wf.item.steps.length : 0;
      return n ? T(base + 'follow-one-action', { count: n }) : T(base + 'follow-one-action-fallback');
    }
    var c = (p.stepIds || []).length;
    return c === 1 ? T(base + 'default-one') : T(base + 'default', { count: c });
  }

  function startPath(p) {
    if (p.kind === 'explore') return go('#/architecture');
    if (p.kind === 'reading-order') return go('#/reading-order');
    if (p.kind === 'what-changed') return go('#/changed');
    if (p.kind === 'review-unfinished') return go('#/progress?filter=unfinished');
    if (p.kind === 'continue') {
      var loc = P.data.lastLocation;
      if (loc && byId[loc.sectionId]) return goToItem(loc.sectionId);
      var next = trackedIds().filter(function (id) { return P.state(id) !== 'completed'; })[0];
      return next ? goToItem(next) : go('#/architecture');
    }
    var first = (p.stepIds || [])[0];
    if (first) goToItem(first);
  }

