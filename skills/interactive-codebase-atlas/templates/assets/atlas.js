/* ============================================================================
   Codebase Atlas — application shell.

   Two inputs, both JSON, neither of them here:
     data/atlas.json  what this repository is        (regenerated by an update)
     data/ui.json     what the atlas says and shows  (curated; never regenerated)

   No repository knowledge and no user-facing copy live in this file. Every
   string, heading, label, nav entry, field table and empty state is looked up
   through window.AtlasUI (assets/templates.js). Reword or reorder the interface
   by editing data/ui.json.

   Both files load from window.__ATLAS__ / window.__ATLAS_UI__ (file://) or fall
   back to fetch (http://).
   ========================================================================== */
