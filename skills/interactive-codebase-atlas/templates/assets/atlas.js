  function $(sel) { return document.querySelector(sel); }
  function txt(s) { return document.createTextNode(s == null ? '' : String(s)); }
  /* Authored prose, inline. `code` and *emphasis* marks are rendered rather than
     shown literally — a visible backtick reads as markdown that failed. Use this
     wherever authored content is spliced beside a label; `txt` is for UI chrome. */
  function mark(s) { return h('span', { text: s == null ? '' : String(s) }); }
  function dash() { return T('common.dash'); }

  function depthOf(item) {
    var level = P.pref('depthPreference') || UI.get('theme.defaultDepth', 'balanced');
    var d = item.depth || {};
    return d[level] || d.balanced || d.simple || d.deep || '';
  }

  function collect() {
    byId = {}; hashes = {};
    var lists = ['components', 'connections', 'workflows', 'entities', 'channels',
                 'subsystems', 'changePlaybooks', 'glossary', 'knowledgeChecks',
                 'openQuestions', 'learningPaths'];
    lists.forEach(function (kind) {
      (A[kind] || []).forEach(function (item) {
        byId[item.id] = { item: item, kind: kind };
        if (item.contentHash) hashes[item.id] = item.contentHash;
        (item.steps || []).forEach(function (s) {
          byId[s.id] = { item: s, kind: 'steps', parent: item };
          if (s.contentHash) hashes[s.id] = s.contentHash;
        });
      });
    });
    ['auth', 'delivery'].forEach(function (k) {
      if (A[k] && A[k].id) { byId[A[k].id] = { item: A[k], kind: k }; hashes[A[k].id] = A[k].contentHash; }
    });
    (A.explorer && A.explorer.groups || []).forEach(function (item) {
      byId[item.id] = { item: item, kind: 'areas' };
      if (item.contentHash) hashes[item.id] = item.contentHash;
    });
    (A.explorer && A.explorer.files || []).forEach(function (item) {
      byId[item.id] = { item: item, kind: 'files' };
      if (item.contentHash) hashes[item.id] = item.contentHash;
    });
    /* Reading-order nodes are tracked items like any other: same ids, same
       progress store, same search index. They stay out of `trackedIds` because
       "files read" and "sections understood" are two different denominators —
       folding them together would silently halve every existing reader's
       percentage the day this collection landed. */
    (A.readingOrder && A.readingOrder.nodes || []).forEach(function (item) {
      byId[item.id] = { item: item, kind: 'readingOrder' };
      if (item.contentHash) hashes[item.id] = item.contentHash;
    });
  }

  /** Ids that count toward overall progress: the things a reader "works through". */
  function trackedIds() {
    var out = [];
    ['components', 'workflows', 'entities', 'channels', 'subsystems', 'changePlaybooks'].forEach(function (k) {
      (A[k] || []).forEach(function (i) { out.push(i.id); });
    });
    ['auth', 'delivery'].forEach(function (k) { if (A[k] && A[k].id) out.push(A[k].id); });
    return out;
  }

  /** Changed-item review includes workflow steps without adding them to the
      overall completion denominator. */
  function changeReviewIds() {
    var out = trackedIds();
    (A.workflows || []).forEach(function (workflow) {
      (workflow.steps || []).forEach(function (step) { out.push(step.id); });
    });
    return out;
  }

  /**
   * The singleton sections (`auth`, `delivery`) carry no title of their own —
   * their heading lives in ui.json, because it is interface copy rather than
   * repository content. Without this they show up in the progress checklist as
   * their raw ids.
   */
  function titleOf(item) {
    return item.title || item.name || item.term || item.task || item.question ||
           UI.get('sectionTitles.' + item.id) || item.id;
  }
  function labelOf(id) { return byId[id] ? titleOf(byId[id].item) : id; }

  /**
   * The computations a ui.json field row can name. Everything a field table
   * cannot read as a plain property lives here — and nowhere else, so adding a
   * derived row is one function plus one line of JSON.
   */
  var COMPUTED = {
    entryPoint: function (c) {
      return c.entryPoint ? c.entryPoint.path + (c.entryPoint.symbol ? ' → ' + c.entryPoint.symbol : '') : '';
    },
    componentConnections: function (c) {
      return (A.connections || []).filter(function (x) { return x.from === c.id || x.to === c.id; })
        .map(function (x) { return labelOf(x.from === c.id ? x.to : x.from) + ' (' + x.mechanism + ')'; })
        .join(', ');
    },
    entityKind: function (e) {
      return (e.dataClass || '') + (e.persistence ? ' · ' + e.persistence : '');
    },
    entityLifecycle: function (e) {
      return e.lifecycleText || (e.lifecycle || []).join(' → ');
    },
    stepSource: function (s) {
      return s.source ? s.source.path + (s.source.symbol ? ' → ' + s.source.symbol : '') : '';
    }
  };
  var CTX = { compute: COMPUTED, label: labelOf };

